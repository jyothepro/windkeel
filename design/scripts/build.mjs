function tokensJson() {
  const color = JSON.parse(read("tokens/color.json"));
  const tokens = [];
  for (const [hue, steps] of Object.entries(color.light.scale)) {
    for (const step of Object.keys(steps)) {
      tokens.push({
        name: `${hue}-${step}`,
        value: { light: color.light.scale[hue][step].$value, dark: color.dark.scale[hue][step].$value },
        usage: `${HUE_NOTES[hue]} step ${step}: ${STEP_ROLES[step - 1]}. Reach for a color-* token instead where one fits.`,
      });
    }
  }
  const ref = (v) => {
    const m = /^\{scale\.([a-z]+)\.(\d+)\}$/.exec(v);
    return m ? `{${m[1]}-${m[2]}}` : v;
  };
  for (const key of Object.keys(color.light.color)) {
    if (!USAGE[key]) throw new Error(`no usage note for color-${key}`);
    tokens.push({
      name: `color-${key}`,
      value: { light: ref(color.light.color[key].$value), dark: ref(color.dark.color[key].$value) },
      usage: USAGE[key],
    });
  }

  const groupsByName = new Map();
  for (const s of F.textStyles) {
    if (!groupsByName.has(s.group)) groupsByName.set(s.group, { name: s.group, family: s.family, styles: [] });
    groupsByName.get(s.group).styles.push({
      name: s.name,
      family: s.family,
      fontSize: px(s.size),
      lineHeight: px(s.leading),
      fontWeight: s.weight,
      ...(s.tracking && { letterSpacing: s.tracking }),
      sample: s.sample,
      usage: s.usage,
    });
  }

  const list = (rows, unit = px) => ({ tokens: rows.map(([name, v, usage]) => ({ name, value: unit(v), usage })) });
  return {
    name: "Windkeel",
    version: 1,
    meta: {
      source: "github",
      repo: "jyothepro/windkeel",
      ref: gitRef(),
      package: "design",
      paths: { tokens: ["design/tokens/color.json", "design/tokens/foundation.mjs"], docs: ["design/guidelines.md"] },
      synced: new Date().toISOString().slice(0, 10),
    },
    color: { themes: [{ id: "light", name: "Light" }, { id: "dark", name: "Dark" }], tokens },
    type: {
      fonts: [],
      families: F.fonts.families,
      groups: [...groupsByName.values()],
    },
    spacing: list(F.spacing),
    radius: list(F.radius),
    shadow: { tokens: F.shadows.map(([name, usage, value]) => ({ name, value, usage })) },
    size: { note: "Control and icon sizes.", ...list([...F.sizes, ...F.layout]) },
    zIndex: list(F.zIndex, String),
  };
}

function gitRef() {
  try {
    const branch = execSync("git rev-parse --abbrev-ref HEAD", { cwd: root }).toString().trim();
    const sha = execSync("git rev-parse --short HEAD", { cwd: root }).toString().trim();
    return `${branch}@${sha}`;
  } catch {
    return "unknown";
  }
}

const write = (rel, text) => {
  const p = join(out, "project", rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, text);
};

