import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "human-workspace-server-files.ts");

const SERVER_FILES = [
  "package.json",
  "package-lock.json",
  "server/server.mjs",
  "server/token-gate.mjs",
  "server/pty-bridge.py",
  "server/public/open.html",
  "server/public/boot.js",
  "server/public/term.html",
  "server/public/term.js",
];

export function render() {
  const entries = SERVER_FILES.map((path) => {
    const bytes = readFileSync(join(here, path));
    const content = bytes.toString("utf8");
    if (!Buffer.from(content, "utf8").equals(bytes)) throw new Error(`${path} is not UTF-8 text`);
    const sha256 = createHash("sha256").update(bytes).digest("hex");
    return `  {\n    path: ${JSON.stringify(path)},\n    sha256: ${JSON.stringify(sha256)},\n    content: ${JSON.stringify(content)},\n  },`;
  });
  return [
    "// GENERATED by src/sandbox/human-workspace-server/embed.mjs — do not edit by hand.",
    "// Edit the files in src/sandbox/human-workspace-server/ and run `npm run embed:human-workspace-server`.",
    "",
    "/** One file of the in-VM workspace server (ADR-0029 §4), embedded so every bundle carries it (#381). */",
    "export interface HumanWorkspaceServerFile {",
    "  /** Relative to the server's directory in the VM. */",
    "  readonly path: string;",
    "  /** SHA-256 of `content` as UTF-8, recorded when this module was generated. */",
    "  readonly sha256: string;",
    "  readonly content: string;",
    "}",
    "",
    "export const HUMAN_WORKSPACE_SERVER_FILES: readonly HumanWorkspaceServerFile[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(out, render());
  console.log(`wrote ${out}`);
}
