import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { RunList } from "../../../../components/run-list.tsx";
import { PlaybookBadge, SourceBadge } from "../../../../components/source-badge.tsx";
import { getTask, listAllRepositories, listRuns, openableTabs } from "../../../../lib/api.ts";
import { time } from "../../../../lib/format.ts";

export const metadata: Metadata = { title: "Task" };

export default async function TaskPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const [task, runs, repos, openable] = await Promise.all([getTask(id), listRuns({ task: id }), listAllRepositories(), openableTabs()]);
  if (!task) notFound();
  const c = task.criteria;

  return (
    <main className="console-main console-main--wide">
      <header className="console-header">
        <div>
          <h1>{task.title}</h1>
          <div className="console-header__sub console-header__source">
            <SourceBadge task={task} openable={openable} />
            <PlaybookBadge playbook={task.playbook} />
            {task.sourceType === "api" ? <span>Filed from the console or the API</span> : null}
            <span>risk {task.riskLevel}</span>
          </div>
        </div>
      </header>

      <section className="console-section">
        <h3>Criteria</h3>
        <p className="oq-muted" style={{ margin: 0 }}>
          {c.provenance === "generated"
            ? `Generated by ${c.generatedBy ?? "a model"}. ${c.approvedBy ? `Approved by ${c.approvedBy}, ${time(c.approvedAt)}.` : "Not yet approved."}`
            : "Extracted from the issue — the author's own words."}
        </p>
        <ol className="oq-stack" style={{ margin: 0, paddingLeft: "var(--space-5)" }}>
          {c.items.map((item) => (
            <li key={item.id}>{item.text}</li>
          ))}
        </ol>
      </section>

      <section className="console-section">
        <h3>Description</h3>
        <p style={{ margin: 0, whiteSpace: "pre-wrap" }}>{task.description}</p>
      </section>

      <section className="console-section">
        <h3>Runs</h3>
        {runs.items.length ? <RunList runs={runs.items} repositories={repos.items} /> : <p className="oq-muted">No runs yet.</p>}
      </section>
    </main>
  );
}
